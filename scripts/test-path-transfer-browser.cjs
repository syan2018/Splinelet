module.exports = async (page, fixture, output) => {
  const assert=require('node:assert/strict');
  const call=(action,args={})=>page.evaluate(({action,args})=>window.traceStudio.call(action,args),{action,args});
  const checks=[];
  const check=(condition,name)=>{assert(condition,name);checks.push(name)};
  await page.locator('input[accept=".json"]').setInputFiles([]);
  await page.locator('input[accept=".json"]').setInputFiles(fixture);
  await page.waitForFunction(async()=>{try{return (await window.traceStudio.call('get_project')).paths.some(p=>/^路径\s*75$/.test(p.name))}catch{return false}});
  await page.locator('.creation-updating').waitFor({state:'hidden'});
  const original=await call('get_project'), id=original.paths.find(p=>/^路径\s*75$/.test(p.name)).id;
  const initial=await call('creation_inspect');
  const owner=initial.creation.objects.find(o=>o.pathIds.includes(id));
  const destination=initial.creation.objects.find(o=>o.name==='头饰');
  const row=()=>page.locator(`[data-tree-path="${id}"]`);
  const target=objectId=>page.locator(`[data-tree-object="${objectId}"]`);
  const wait=async(objectId)=>{
    await page.waitForFunction(async({id,objectId})=>{try{
      const p=await window.traceStudio.call('get_project');
      return p.creation.objects.find(o=>o.pathIds.includes(id))?.id===objectId && !(await window.traceStudio.call('creation_inspect')).errors.length;
    }catch{return false}}, {id,objectId});
    await page.locator('.creation-updating').waitFor({state:'hidden'});
    await row().waitFor({state:'visible'});
  };
  if(await target(owner.id).getAttribute('aria-expanded')==='false')await target(owner.id).getByRole('button',{name:'展开'+owner.name,exact:true}).click();
  await row().click();
  if(await target(destination.id).getAttribute('aria-expanded')==='true')await target(destination.id).getByRole('button',{name:'折叠'+destination.name,exact:true}).click();
  await row().dragTo(target(destination.id));await wait(destination.id);
  check(await target(destination.id).getAttribute('aria-expanded')==='true','drop into a collapsed collection reveals its new child');
  check((await call('state')).creation.selection.kind==='path'&&(await call('state')).creation.selection.ids.includes(id),'reparent keeps single-path selection');
  let moved=await call('get_project');
  check(moved.paths.find(p=>p.id===id).groupId===destination.groupId,'path group metadata follows the collection for saved/exported projects');
  check(JSON.stringify(moved.creation.objects.find(o=>o.id===owner.id).modifiers)===JSON.stringify(initial.creation.objects.find(o=>o.id===owner.id).modifiers),'source modifier remains unchanged');
  await page.screenshot({path:output+'/path75-moved.png',scale:'css'});
  await page.keyboard.press('Control+z');await wait(owner.id);
  check(JSON.stringify((await call('get_project')).paths)===JSON.stringify(original.paths),'one undo restores the exact source paths and original membership');
  await page.keyboard.press('Control+Shift+z');await wait(destination.id);
  check((await call('get_project')).creation.objects.find(o=>o.id===destination.id).pathIds.includes(id),'redo restores the transfer and reveal');
  await row().dragTo(target(owner.id));await wait(owner.id);
  check(!(await call('creation_inspect')).errors.length,'path can be dragged back out of a painted modifier collection');
  await row().dragTo(target(destination.id));await wait(destination.id);
  await page.locator('footer').getByText('已保存到此浏览器 · 可绑定工程文件',{exact:true}).waitFor();
  await page.reload();
  await page.waitForFunction(async({id,objectId})=>{try{return (await window.traceStudio.call('get_project')).creation?.objects.find(o=>o.pathIds.includes(id))?.id===objectId}catch{return false}},{id,objectId:destination.id});
  check((await call('get_project')).paths.find(p=>p.id===id).groupId===destination.groupId,'autosave/reload preserves collection assignment');
  return {passed:checks.length,checks};
};
